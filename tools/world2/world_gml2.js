// Write scripts/world_rooms/world_rooms.gml for Cedar & Sea's world (the blueprint's rooms, tools/world2): which rooms
// are outdoors, every room's place name (an interior: the district its door is in - the old room's name), fishing
// water, the road cells (the player's road boost), the resource spawn areas, and the alias table that sends the old
// rooms' names ("rm_downtown") to the new rooms they're part of (for the villagers' schedules and the tests).
//   node tools/world2/world_gml2.js      (after the rooms are built: layout_cells must know the areas)
const fs = require("fs");
const path = require("path");
const {ROOMS} = require("../world/world.js");
const {REUSED} = require("../world/interior_data.js");
const A = require("./areas_build.js");
const ROOT = path.join(__dirname, "..", "..");

const B = A.all(), NEWROOMS = Object.keys(B.rooms);
const outdoors = ["rm_1", ...NEWROOMS];
const AREA_NAME = Object.fromEntries(Object.entries(A.ROOM_OF).map(([n, id]) => [id, n]));
const names = {rm_mine: "The Mine", rm_12: "Player Farm", rm_123: "Player Farm", rm_1: "Player Farm"};
for(const id of NEWROOMS) names[id] = AREA_NAME[id];
// an interior is named for its old district (the room its door used to be in)
for(const [id, R] of Object.entries(ROOMS)) for(const b of R.buildings || []) names[b.room] = R.name;
for(const [r, [o]] of Object.entries(REUSED)) names[r] = ROOMS[o].name;

const water = {};
for(const id of NEWROOMS) if(A.WATER[id]) water[id] = A.WATER[id];

const roads = {};
for(const id of NEWROOMS){
	const m = B.rooms[id].map;
	roads[id] = {w: m[0].length, grid: m.map(r => [...r].map(c => c === ":" ? "1" : "0").join("")).join("")};
}

const KINDS = {
	town:  [["weeds", 45], ["bush", 25], ["stone", 25], ["forage_herb", 5]],
	rural: [["oak", 18], ["pine", 14], ["bush", 15], ["weeds", 18], ["stone", 15], ["forage_herb", 12], ["forage_mushroom", 8]],
	deep:  [["oak", 22], ["pine", 22], ["bush", 12], ["weeds", 6], ["stone", 4], ["forage_herb", 16], ["forage_mushroom", 16], ["forage_toadstool", 8]],
	wild:  [["oak", 20], ["pine", 20], ["bush", 12], ["weeds", 8], ["stone", 6], ["forage_herb", 12], ["forage_mushroom", 14], ["forage_toadstool", 8]],
	shore: [["stone", 40], ["boulder", 15], ["weeds", 25], ["bush", 15], ["copper_vein", 5]],
	cliff: [["stone", 40], ["boulder", 8], ["copper_vein", 24], ["coal_vein", 10], ["iron_vein", 10], ["silver_vein", 5], ["gold_vein", 3]],
};
const areas = [];
for(const id of NEWROOMS){
	const S = B.rooms[id];
	for(const [n, c] of Object.entries(S.areas || {})){
		const kind = S.areaKinds[n], cells = (c[2] - c[0] + 1) * (c[3] - c[1] + 1);
		if(!kind) continue;
		const max = Math.max(2, Math.min(kind === "deep" ? 14 : kind === "wild" ? 9 : 6, Math.round(cells / (kind === "town" ? 90 : 40))));
		areas.push({room: id, area: n, max, perDay: Math.max(1, Math.round(max / 4)), start: Math.round(max * 0.7), kinds: KINDS[kind]});
	}
}

const q = s => JSON.stringify(s);
const gml = `// Generated by tools/world2/world_gml2.js from the blueprint (design/map) - don't edit by hand.
// Cedar & Sea's rooms: which are outdoors, the place each room belongs to, fishing water, road cells, the resource
// spawn areas, and the old rooms' names (the 25 rooms before the merge) mapped to the rooms they're part of now.

/// @description The outdoor rooms, by name.
function world_outdoors(){
	static t = [${outdoors.map(q).join(", ")}];
	return t;
}

/// @description Whether a room (by name) is outdoors.
function world_is_outdoors(_name){
	static t = {${outdoors.map(n => `${n}: true`).join(", ")}};
	return t[$ _name] ?? false;
}

/// @description The place a room is in (an interior gives the district its door is in), or undefined.
function world_place_name(_name){
	static t = {${Object.entries(names).map(([k, v]) => `${k}: ${q(v)}`).join(", ")}};
	return t[$ _name];
}

/// @description What fish a room's water has: "sea", "river", or undefined (ponds).
function world_water(_name){
	static t = {${Object.entries(water).map(([k, v]) => `${k}: ${q(v)}`).join(", ")}};
	return t[$ _name];
}

/// @description The room an old room's name now means (rm_downtown -> rm_beirut), or the name itself. Its spots are
/// in that room as "<old room>__<spot>" (layout_point and sched_place look there).
function world_alias(_name){
	static t = {${Object.entries(A.ALIAS).map(([k, v]) => `${k}: ${q(v)}`).join(", ")}};
	return t[$ _name] ?? _name;
}

/// @description Whether a cell of an outdoor room is road (cobbles), for the player's road boost.
function world_is_road(_name, _cx, _cy){
	static t = {
${Object.entries(roads).map(([k, v]) => `\t\t${k}: {w: ${v.w}, grid: "${v.grid}"},`).join("\n")}
	};
	var r = t[$ _name];
	if(r == undefined || _cx < 0 || _cy < 0 || _cx >= r.w) return false;
	var i = _cy * r.w + _cx;
	return i < string_length(r.grid) && string_char_at(r.grid, i + 1) == "1";
}

/// @description Resource spawn areas of the generated rooms (resource_areas in scripts/gathering appends these).
function world_resource_areas(){
	return [
${areas.map(a => `\t\t{room: "${a.room}", cells: layout_cells("${a.room}", "${a.area}"), max: ${a.max}, perDay: ${a.perDay}, start: ${a.start},\n\t\t kinds: [${a.kinds.map(k => `["${k[0]}", ${k[1]}]`).join(", ")}]},`).join("\n")}
	];
}
`;
fs.writeFileSync(path.join(ROOT, "scripts", "world_rooms", "world_rooms.gml"), gml);
console.log(`world_rooms.gml: ${outdoors.length} outdoor rooms, ${areas.length} resource areas, ${Object.keys(A.ALIAS).length} old names`);
