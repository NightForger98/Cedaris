// Write scripts/world_rooms/world_rooms.gml from the world data: which rooms are outdoors, every room's place name,
// fishing water, the road cells (the player's road boost) and the resource spawn areas.
//   node tools/world/world_gml.js      (after make_specs.js; build.js must have run so layout_cells knows the areas)
const fs = require("fs");
const path = require("path");
const {ROOMS, GRID} = require("./world.js");
const {NEW, REUSED} = require("./interior_data.js");
const ROOT = path.join(__dirname, "..", "..");
const spec = id => require(path.join(ROOT, "tools", "rooms", "specs", id + ".js"));

const outdoors = GRID.flat();
const names = {rm_mine: "The Mine", rm_12: "Player Farm", rm_123: "Player Farm"};
for(const id of outdoors) names[id] = ROOMS[id].name;
for(const [id, R] of Object.entries(ROOMS)) for(const b of R.buildings || []) names[b.room] = R.name;
for(const [r, [o]] of Object.entries(REUSED)) names[r] = ROOMS[o].name;

const water = {};
for(const id of outdoors){
	const R = ROOMS[id];
	if(R.sea) water[id] = "sea";
	else if(R.river) water[id] = "river";
}

// Road cells (":" in the map): one digit per cell, "1" a road
const roads = {};
for(const id of outdoors){
	const m = spec(id).map;
	roads[id] = {w: m[0].length, grid: m.map(r => [...r].map(c => c === ":" ? "1" : "0").join("")).join("")};
}

// What grows where
const KINDS = {
	town:  [["weeds", 45], ["bush", 25], ["stone", 25], ["forage_herb", 5]],
	rural: [["oak", 18], ["pine", 14], ["bush", 15], ["weeds", 18], ["stone", 15], ["forage_herb", 12], ["forage_mushroom", 8]],
	// a dense wood (Whispering Woods): thick with trees, and the valley's best forage
	deep:  [["oak", 22], ["pine", 22], ["bush", 12], ["weeds", 6], ["stone", 4], ["forage_herb", 16], ["forage_mushroom", 16], ["forage_toadstool", 8]],
	wild:  [["oak", 20], ["pine", 20], ["bush", 12], ["weeds", 8], ["stone", 6], ["forage_herb", 12], ["forage_mushroom", 14], ["forage_toadstool", 8]],
	shore: [["stone", 40], ["boulder", 15], ["weeds", 25], ["bush", 15], ["copper_vein", 5]],
	cliff: [["stone", 40], ["boulder", 8], ["copper_vein", 24], ["coal_vein", 10], ["iron_vein", 10], ["silver_vein", 5], ["gold_vein", 3]],
};
const areas = [];
for(const id of outdoors){
	if(ROOMS[id].farm) continue;
	const R = ROOMS[id], a = spec(id).areas || {};
	for(const [n, c] of Object.entries(a)){
		const cells = (c[2] - c[0] + 1) * (c[3] - c[1] + 1);
		let kind = n.startsWith("shore") ? "shore" : n.startsWith("cliff") ? "cliff" : ["nw", "ne", "sw", "se"].includes(n) ? (R.dense ? "deep" : R.kind) : null;
		if(!kind) continue;
		const max = Math.max(2, Math.min(kind === "deep" ? 28 : kind === "wild" ? 16 : 10, Math.round(cells / (kind === "town" ? 90 : 45))));
		areas.push({room: id, area: n, max, perDay: Math.max(1, Math.round(max / 4)), start: Math.round(max * 0.7), kinds: KINDS[kind]});
	}
}

const q = s => JSON.stringify(s);
const gml = `// Generated by tools/world/world_gml.js from tools/world/world.js - don't edit by hand.
// The new world's rooms: which are outdoors, the place each room belongs to, fishing water, road cells and the
// resource spawn areas of the generated outdoor rooms.

/// @description The outdoor rooms, by name.
function world_outdoors(){
	static t = [${outdoors.map(q).join(", ")}];
	return t;
}

/// @description Whether a room (by name) is outdoors.
function world_is_outdoors(_name){
	static t = {${outdoors.map(n => `${n}: true`).join(", ")}};
	return t[$ _name] ?? false;
}

/// @description The place a room is in (an interior gives the place its door is in), or undefined.
function world_place_name(_name){
	static t = {${Object.entries(names).map(([k, v]) => `${k}: ${q(v)}`).join(", ")}};
	return t[$ _name];
}

/// @description What fish a room's water has: "sea", "river", or undefined (ponds).
function world_water(_name){
	static t = {${Object.entries(water).map(([k, v]) => `${k}: ${q(v)}`).join(", ")}};
	return t[$ _name];
}

/// @description Whether a cell of an outdoor room is road (cobbles), for the player's road boost.
function world_is_road(_name, _cx, _cy){
	static t = {
${Object.entries(roads).map(([k, v]) => `\t\t${k}: {w: ${v.w}, grid: "${v.grid}"},`).join("\n")}
	};
	var r = t[$ _name];
	if(r == undefined || _cx < 0 || _cy < 0 || _cx >= r.w) return false;
	var i = _cy * r.w + _cx;
	return i < string_length(r.grid) && string_char_at(r.grid, i + 1) == "1";
}

/// @description Resource spawn areas of the generated rooms (resource_areas in scripts/gathering appends these).
function world_resource_areas(){
	return [
${areas.map(a => `\t\t{room: "${a.room}", cells: layout_cells("${a.room}", "${a.area}"), max: ${a.max}, perDay: ${a.perDay}, start: ${a.start},\n\t\t kinds: [${a.kinds.map(k => `["${k[0]}", ${k[1]}]`).join(", ")}]},`).join("\n")}
	];
}
`;
const dir = path.join(ROOT, "scripts", "world_rooms");
fs.mkdirSync(dir, {recursive: true});
fs.writeFileSync(path.join(dir, "world_rooms.gml"), gml);
const yy = path.join(dir, "world_rooms.yy");
if(!fs.existsSync(yy)){
	fs.writeFileSync(yy, `{\n  "$GMScript":"v1",\n  "%Name":"world_rooms",\n  "isCompatibility":false,\n  "isDnD":false,\n  "name":"world_rooms",\n  "parent":{\n    "name":"Scripts",\n    "path":"folders/Scripts.yy",\n  },\n  "resourceType":"GMScript",\n  "resourceVersion":"2.0",\n}`);
	const yypPath = path.join(ROOT, "NewHarvest.yyp");
	let yyp = fs.readFileSync(yypPath, "utf8");
	const nl = yyp.includes("\r\n") ? "\r\n" : "\n";
	const entry = '    {"id":{"name":"world_rooms","path":"scripts/world_rooms/world_rooms.yy",},},';
	if(!yyp.includes(entry)){ yyp = yyp.replace('"resources":[' + nl, '"resources":[' + nl + entry + nl); fs.writeFileSync(yypPath, yyp); }
}
console.log(`world_rooms.gml: ${outdoors.length} outdoor rooms, ${areas.length} resource areas`);
