// Write _str centred on x at y (top) into a PNG image (tools/rooms/png.js) at scale _sc, outlined in near-black
function text(img, str, x, y, sc, col){
	const put = (px, py, c) => { if(px < 0 || py < 0 || px >= img.w || py >= img.h) return; const k = (py * img.w + px) * 4; img.px[k] = c[0]; img.px[k + 1] = c[1]; img.px[k + 2] = c[2]; img.px[k + 3] = 255; };
	str = str.toUpperCase();
	let px0 = Math.round(x - str.length * 6 * sc / 2);
	for(const ch of str){
		const rows = (F[ch] || F[" "]).split(" ");
		for(const pass of [0, 1]) for(let r = 0; r < 7; r++) for(let c = 0; c < 5; c++) if(rows[r][c] === "1"){
			if(pass === 0){ for(let oy = -1; oy <= 1; oy++) for(let ox = -1; ox <= 1; ox++) for(let yy = 0; yy < sc; yy++) for(let xx = 0; xx < sc; xx++) put(px0 + c * sc + xx + ox, y + r * sc + yy + oy, [24, 20, 18]); }
			else for(let yy = 0; yy < sc; yy++) for(let xx = 0; xx < sc; xx++) put(px0 + c * sc + xx, y + r * sc + yy, col);
		}
		px0 += 6 * sc;
	}
}
